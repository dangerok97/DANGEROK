"""Durable identity linking and inbound AI Core delivery for WhatsApp.

A WhatsApp sender is never an ORA user until they have sent a short-lived code
generated by an authenticated ORA session. Phone and message text are encrypted
at rest; lookup keys are keyed HMACs, not reversible phone numbers.
"""
from __future__ import annotations

import hashlib
import json
import logging
import re
import secrets
from datetime import datetime, timedelta, timezone

from pymongo import ReturnDocument
from pymongo.errors import DuplicateKeyError

from whatsapp.cloud import CloudConfig
from whatsapp.handoff import render_core_answer_for_whatsapp
from whatsapp.media import MediaNotUsable, fetch_whatsapp_media, transcribe_voice
from whatsapp.parity import public_whatsapp_parity_status
from whatsapp.alerts import template_settings, in_service_window

log = logging.getLogger("ora.whatsapp")

ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
LINK_MINUTES = 10
MAX_ATTEMPTS_PER_DAY = 12


def now() -> datetime:
    return datetime.now(timezone.utc)


def _sender_message_moment(message: dict, received_at: datetime) -> datetime:
    """The verified customer event, never the eventual AI processing time.

    A missing Meta timestamp safely falls back to the first signed webhook
    receipt. Duplicate webhook callbacks cannot reopen the service window.
    """
    value = message.get("sent_at")
    if isinstance(value, int) and not isinstance(value, bool):
        try:
            sent = datetime.fromtimestamp(value, tz=timezone.utc)
            if sent <= received_at:
                return sent
        except (ValueError, OSError, OverflowError):
            pass
    return received_at


def _pair_command(text: str) -> str | None:
    match = re.fullmatch(r"\s*COLLEGA\s+([A-HJ-NP-Z2-9]{10})\s*", text, re.IGNORECASE)
    return match.group(1).upper() if match else None


# User opt-out must work from WhatsApp itself, even when AI/provider is down.
# Exact-message matching prevents e.g. "Cosa significa STOP?" disabling it.
_ALERT_OPTOUT = re.compile(
    r"(?i)^\s*(?:"
    r"STOP(?:\s+(?:NOTIFICHE|AVVISI))?"
    r"|DISATTIVA\s+(?:(?:LE|GLI)\s+)?(?:NOTIFICHE|AVVISI)(?:\s+WHATSAPP)?"
    r"|NON\s+(?:MANDARMI|INVIARMI)\s+PI[UÙ]\s+(?:NOTIFICHE|AVVISI)"
    r")\s*[.!]?\s*$"
)


def _is_alert_optout(text: str) -> bool:
    return bool(_ALERT_OPTOUT.fullmatch(str(text or "")))


async def ensure_indexes(db) -> None:
    await db.whatsapp_links.create_index("user_id", unique=True)
    await db.whatsapp_links.create_index("phone_hash", unique=True)
    await db.whatsapp_link_codes.create_index("user_id", unique=True)
    await db.whatsapp_link_codes.create_index("token_hash", unique=True)
    await db.whatsapp_link_codes.create_index("expires_at", expireAfterSeconds=0)
    await db.whatsapp_inbox.create_index([("status", 1), ("next_attempt_at", 1), ("received_at", 1)])
    await db.whatsapp_inbox.create_index("expires_at", expireAfterSeconds=0)
    await db.whatsapp_sender_locks.create_index("lease_until", expireAfterSeconds=0)
    from whatsapp.alerts import ensure_indexes as ensure_alert_indexes
    await ensure_alert_indexes(db)


class WhatsAppService:
    def __init__(self, db, config: CloudConfig | None = None):
        self.db = db
        self.config = config or CloudConfig.load()

    async def status(self, user_id: str) -> dict:
        link = await self.db.whatsapp_links.find_one({"user_id": user_id}, {"_id": 0})
        # A template name in Railway is only a request to inspect Meta.
        # A genuine APPROVED UTILITY template is what permits outreach.
        from whatsapp.template_approval import approval_status

        template = template_settings()
        approval = await approval_status(self.config) if template else "not_configured"
        try:
            parity = public_whatsapp_parity_status()
        except Exception as exc:
            # A status badge must never make pairing/unlinking unavailable.
            # Log no personal details or provider secrets.
            log.warning("WhatsApp shared catalog unavailable: category=%s", type(exc).__name__)
            parity = {
                "shared_ai_core": True,
                "shared_capability_count": None,
                "capability_contract_version": None,
                "device_handoff_supported": True,
            }
        return {
            **parity,
            "configured": True,
            "linked": bool(link),
            "phone_last4": link.get("phone_last4") if link else None,
            "display_number": self.config.display_number or None,
            "notifications_enabled": bool(
                link and link.get("notifications_enabled") is True
                and link.get("opted_in_at")
            ),
            "notifications_detail_enabled": bool(
                link and link.get("notifications_enabled") is True
                and link.get("opted_in_at")
                and link.get("notifications_detail_enabled") is True
                and link.get("details_opted_in_at")
            ),
            "template_configured": bool(template),
            "template_approval_status": approval,
            "notification_channel_ready": bool(
                link and link.get("notifications_enabled") is True
                and link.get("opted_in_at")
                and (in_service_window(link) or approval == "approved_dynamic")
            ),
        }

    async def issue_pairing_code(self, user_id: str) -> dict:
        """The code is shown only in the authenticated ORA app; never sent to third parties."""
        code = "".join(secrets.choice(ALPHABET) for _ in range(10))
        timestamp = now()
        expiry = timestamp + timedelta(minutes=LINK_MINUTES)
        await self.db.whatsapp_link_codes.update_one(
            {"user_id": user_id},
            {"$set": {
                "token_hash": self.config.fingerprint("pair", code),
                "expires_at": expiry,
                "created_at": timestamp,
            }},
            upsert=True,
        )
        return {
            "code": code,
            "expires_at": expiry.isoformat(),
            "display_number": self.config.display_number or None,
            "instruction": "Invia COLLEGA seguito dal codice al numero WhatsApp di ORA.",
        }

    async def disconnect(self, user_id: str) -> None:
        await disconnect_account(self.db, user_id)

    async def _limit_pair_attempts(self, phone_hash: str) -> bool:
        from security.rate_limit import _bucket_id
        key, expires = _bucket_id("whatsapp_pair", phone_hash, window_seconds=86400)
        res = await self.db.rate_limit_buckets.find_one_and_update(
            {"_id": key},
            {"$inc": {"count": 1}, "$setOnInsert": {"expires_at": expires, "scope": "whatsapp_pair"}},
            upsert=True,
            return_document=ReturnDocument.AFTER,
        )
        return int((res or {}).get("count", 0)) <= MAX_ATTEMPTS_PER_DAY

    async def pair(
        self, sender: str, code: str, *,
        message_at: datetime | None = None,
    ) -> tuple[str, str | None]:
        phone_hash = self.config.fingerprint("phone", sender)
        if not await self._limit_pair_attempts(phone_hash):
            return "Troppi tentativi di collegamento. Riprova domani dall'app ORA.", None
        record = await self.db.whatsapp_link_codes.find_one_and_delete({
            "token_hash": self.config.fingerprint("pair", code),
            "expires_at": {"$gt": now()},
        })
        if not record:
            existing = await self.db.whatsapp_links.find_one({"phone_hash": phone_hash}, {"_id": 0})
            if existing:
                return "Questo numero WhatsApp è già collegato a ORA.", existing["user_id"]
            return "Codice errato o scaduto. Apri ORA → Connessioni e servizi e genera un nuovo codice.", None
        user_id = record["user_id"]
        existing = await self.db.whatsapp_links.find_one({"phone_hash": phone_hash}, {"_id": 0})
        if existing and existing["user_id"] != user_id:
            return "Questo numero è già collegato a un altro account. Scollegalo dal vecchio account prima di riprovare.", None
        timestamp = now()
        authenticated_at = message_at if isinstance(message_at, datetime) else timestamp
        if authenticated_at.tzinfo is None:
            authenticated_at = authenticated_at.replace(tzinfo=timezone.utc)
        if authenticated_at > timestamp:
            authenticated_at = timestamp
        previous = await self.db.whatsapp_links.find_one({"user_id": user_id}, {"_id": 0})
        same_phone = bool(previous and previous.get("phone_hash") == phone_hash)
        row = {
            "user_id": user_id,
            "phone_hash": phone_hash,
            "phone_enc": self.config.encrypt(sender),
            "phone_last4": sender[-4:],
            "last_session_id": previous.get("last_session_id") if same_phone else None,
            "linked_at": timestamp,
            "last_inbound_at": authenticated_at,
            "notifications_enabled": False,
        }
        try:
            await self.db.whatsapp_links.replace_one({"user_id": user_id}, row, upsert=True)
        except DuplicateKeyError:
            # Unique indexes make cross-account association fail closed under races.
            return "Il collegamento non è riuscito. Riprova dall'app ORA.", None
        return "WhatsApp collegato a ORA. Puoi scrivermi qui: userò il tuo stesso account e le tue memorie dell'app.", user_id

    async def persist_incoming(self, message: dict) -> bool:
        sender = message["from"]
        mid = message["id"]
        key = hashlib.sha256((self.config.phone_number_id + ":" + mid).encode()).hexdigest()
        timestamp = now()
        sender_at = _sender_message_moment(message, timestamp)
        try:
            result = await self.db.whatsapp_inbox.update_one(
                {"_id": key},
                {"$setOnInsert": {
                    "provider_message_id": mid,
                    "phone_hash": self.config.fingerprint("phone", sender),
                    "phone_enc": self.config.encrypt(sender),
                    "text_enc": self.config.encrypt(message.get("text") or ""),
                    # Meta media ids and captions belong to this user message,
                    # so retain only encrypted metadata until delivery.
                    "media_enc": self.config.encrypt(json.dumps(message["media"]))
                        if isinstance(message.get("media"), dict) else None,
                    "kind": (message.get("type") or "unknown")[:32],
                    "status": "received",
                    "attempts": 0,
                    "next_attempt_at": timestamp,
                    "received_at": timestamp,
                    "service_window_started_at": sender_at,
                    "expires_at": timestamp + timedelta(days=7),
                }},
                upsert=True,
            )
            if result.upserted_id:
                # Only newly persisted signed inbound messages extend the
                # user-service window. Model delays and Meta webhook replays do not.
                await self.db.whatsapp_links.update_one(
                    {"phone_hash": self.config.fingerprint("phone", sender)},
                    {"$max": {"last_inbound_at": sender_at}},
                )
            return bool(result.upserted_id)
        except DuplicateKeyError:
            return False

    async def claim_next(self) -> dict | None:
        timestamp = now()
        return await self.db.whatsapp_inbox.find_one_and_update(
            {
                "status": {"$in": ["received", "ready", "processing"]},
                "next_attempt_at": {"$lte": timestamp},
                "$or": [{"status": {"$in": ["received", "ready"]}},
                        {"status": "processing", "lease_until": {"$lt": timestamp}}],
            },
            {"$set": {
                "status": "processing",
                "lease_until": timestamp + timedelta(minutes=20),
            }},
            sort=[("received_at", 1)],
            return_document=ReturnDocument.AFTER,
        )

    async def _acquire_sender(self, item: dict) -> bool:
        """Serialize turns from the same phone across API replicas."""
        timestamp = now()
        try:
            held = await self.db.whatsapp_sender_locks.find_one_and_update(
                {
                    "_id": item["phone_hash"],
                    "$or": [{"lease_until": {"$lt": timestamp}}, {"lease_until": {"$exists": False}}],
                },
                {"$set": {"owner": item["_id"], "lease_until": timestamp + timedelta(minutes=20)}},
                upsert=True,
                return_document=ReturnDocument.AFTER,
            )
            return bool(held and held.get("owner") == item["_id"])
        except DuplicateKeyError:
            # Another process owns this sender. Defer without counting a failure.
            return False

    async def _answer_ai(
        self, user_id: str, linked: dict, body: str, incoming_id: str,
        *, attachments: list | None = None,
    ) -> str:
        """Use precisely the app's AI Core orchestration, not a second chatbot."""
        from conversation_engine.ai_core.orchestrator import AICoreOrchestrator

        core = AICoreOrchestrator(self.db)
        session_id = linked.get("last_session_id")
        if session_id:
            kwargs = {
                "text": body, "response_channel": "text",
                "client_message_id": "wa_" + hashlib.sha256(incoming_id.encode()).hexdigest()[:48],
            }
            if attachments:
                kwargs["attachments"] = attachments
            answer = await core.message(user_id, session_id, **kwargs)
            if answer.get("error") in ("not_found", "session_closed"):
                answer = None
        else:
            answer = None
        if answer is None:
            kwargs = {
                "text": body, "origin": "whatsapp",
                "entry_point": "whatsapp", "response_channel": "text",
            }
            if attachments:
                kwargs["attachments"] = attachments
            answer = await core.start(user_id, **kwargs)
            if answer.get("ok") and answer.get("session_id"):
                await self.db.whatsapp_links.update_one(
                    {"user_id": user_id, "phone_hash": linked["phone_hash"]},
                    {"$set": {"last_session_id": answer["session_id"]}},
                )
        if not answer.get("ok"):
            raise RuntimeError("AI Core did not return a successful turn")
        text = render_core_answer_for_whatsapp(answer)
        return text or "Ho ricevuto il messaggio, ma non ho ancora una risposta verificata. Riprova tra poco."

    async def prepare_reply(self, item: dict) -> tuple[str, str | None]:
        sender = self.config.decrypt(item["phone_enc"])
        body = self.config.decrypt(item["text_enc"])
        phone_hash = item["phone_hash"]
        code = _pair_command(body) if item.get("kind") == "text" else None
        if code:
            return await self.pair(
                sender, code,
                message_at=item.get("service_window_started_at") or item.get("received_at"),
            )
        linked = await self.db.whatsapp_links.find_one({"phone_hash": phone_hash}, {"_id": 0})
        if not linked:
            return ("Per parlarmi qui, apri ORA → Connessioni e servizi → WhatsApp. "
                    "Genera il codice e invia COLLEGA seguito dal codice in questa chat."), None
        kind = str(item.get("kind") or "")
        if kind == "text" and _is_alert_optout(body):
            # An authenticated pairing + a signed sender is enough to REVOKE
            # consent; no LLM/skill choice may intercept this preference.
            from whatsapp.alerts import set_opt_in
            await set_opt_in(self.db, linked["user_id"], False)
            # The signed webhook already fixed last_inbound_at at the
            # customer's message time (or first receipt if no valid stamp).
            # Never extend Meta's service window at delayed STOP processing.
            return (
                "Avvisi automatici WhatsApp disattivati. "
                "Continuerò a rispondere alle tue domande qui. "
                "Puoi riattivare gli avvisi da ORA → Connessioni e servizi → WhatsApp."
            ), linked["user_id"]
        attachments: list[dict] = []
        if kind in ("image", "document", "audio"):
            try:
                if not item.get("media_enc"):
                    raise MediaNotUsable("missing_media_reference")
                metadata = json.loads(self.config.decrypt(item["media_enc"]))
                if not isinstance(metadata, dict):
                    raise MediaNotUsable("missing_media_metadata")
                raw, mime = await fetch_whatsapp_media(
                    access_token=self.config.access_token,
                    version=self.config.version,
                    media_id=str(metadata.get("id") or ""),
                    kind=kind,
                    declared_mime=str(metadata.get("mime_type") or ""),
                )
                if kind == "audio":
                    # Voice notes are conversational text after transcription;
                    # the full audio is not stored permanently by WhatsApp bridge.
                    body = await transcribe_voice(raw, mime)
                else:
                    from conversation_engine.ai_core.files.service import ContextFileService

                    defaults = {
                        "image/jpeg": "foto.jpg",
                        "image/png": "foto.png",
                        "image/webp": "foto.webp",
                        "image/heic": "foto.heic",
                        "application/pdf": "documento.pdf",
                    }
                    filename = str(metadata.get("filename") or "").strip()[:180]
                    if not filename:
                        filename = defaults.get(mime, "allegato")
                    uploaded = await ContextFileService(self.db).upload_and_bind(
                        user_id=linked["user_id"], content=raw,
                        filename=filename, mime_type=mime,
                    )
                    if not uploaded.get("ok") or not uploaded.get("file_id"):
                        raise MediaNotUsable("file_ingestion_unavailable")
                    attachments = [{"file_id": uploaded["file_id"]}]
                    if not body.strip():
                        body = (
                            "Guarda la foto che ti ho appena inviato e dimmi cosa vedi."
                            if kind == "image"
                            else "Leggi il documento che ti ho appena inviato e aiutami a capirlo."
                        )
            except MediaNotUsable as exc:
                # Expose a human response, not a false claim of having seen
                # the file or an endless retry of an invalid attachment.
                if kind == "audio":
                    return (
                        "Non riesco a trascrivere questo vocale adesso. "
                        "Puoi riprovare oppure scrivermi il messaggio?"
                    ), linked["user_id"]
                return (
                    "Non riesco a leggere questo allegato adesso. "
                    "Puoi reinviarlo o aprirlo direttamente nell'app ORA?"
                ), linked["user_id"]
        elif kind not in ("text", "location", "interactive", "button"):
            return (
                "Questo formato non è ancora elaborabile su WhatsApp. "
                "Puoi descrivermelo a parole oppure aprire l'app ORA."
            ), linked["user_id"]
        if not body.strip():
            return "Scrivimi cosa desideri fare.", linked["user_id"]
        if len(body) > 5000:
            return "Il messaggio è troppo lungo. Inviami un testo più breve.", linked["user_id"]
        # The signed webhook already recorded sender activity. Delayed AI
        # execution cannot redefine the service window for proactive outreach.
        return await self._answer_ai(
            linked["user_id"], linked, body, item["provider_message_id"],
            attachments=attachments,
        ), linked["user_id"]

    async def process_one(self) -> bool:
        item = await self.claim_next()
        if not item:
            return False
        item_id = item["_id"]
        if not await self._acquire_sender(item):
            await self.db.whatsapp_inbox.update_one(
                {"_id": item_id, "status": "processing"},
                {"$set": {"status": "received", "next_attempt_at": now() + timedelta(seconds=3)}},
            )
            return True
        try:
            if item.get("reply_enc"):
                # The cognition result is already durable: a transport retry must
                # NOT re-execute AI tools or side effects.
                text = self.config.decrypt(item["reply_enc"])
                user_id = item.get("reply_user_id")
            else:
                text, user_id = await self.prepare_reply(item)
                await self.db.whatsapp_inbox.update_one(
                    {"_id": item_id, "status": "processing"},
                    {"$set": {
                        "reply_enc": self.config.encrypt(text),
                        "reply_user_id": user_id,
                    }},
                )
            # Revocation/phone reassignment fence: no personal reply after unlink.
            if user_id:
                current = await self.db.whatsapp_links.find_one(
                    {"user_id": user_id, "phone_hash": item["phone_hash"]}, {"_id": 0})
                if not current:
                    await self.db.whatsapp_inbox.update_one(
                        {"_id": item_id}, {"$set": {"status": "discarded", "phone_enc": None,
                                                "text_enc": None, "media_enc": None, "reply_enc": None}})
                    return True
            recipient = self.config.decrypt(item["phone_enc"])
            await self.config.send_text(recipient, text)
            await self.db.whatsapp_inbox.update_one(
                {"_id": item_id},
                {"$set": {"status": "delivered", "delivered_at": now(), "phone_enc": None,
                          "text_enc": None, "media_enc": None, "reply_enc": None}},
            )
        except Exception as exc:
            # Avoid all secrets, text, names and phone numbers in logs.
            attempts = int(item.get("attempts", 0)) + 1
            failed = attempts >= 5
            await self.db.whatsapp_inbox.update_one(
                {"_id": item_id},
                {"$set": {
                    "status": "failed" if failed else "ready" if item.get("reply_enc") else "received",
                    "next_attempt_at": now() + timedelta(seconds=min(120, 5 * (2 ** min(attempts, 5)))),
                    "lease_until": now(),
                }, "$inc": {"attempts": 1}},
            )
            from whatsapp.cloud import CloudSendError
            if isinstance(exc, CloudSendError):
                log.warning(
                    "WhatsApp delivery rejected: http=%s meta_code=%s meta_subcode=%s",
                    exc.status, exc.code, exc.subcode,
                )
            else:
                log.warning("WhatsApp delivery attempt failed: category=%s", type(exc).__name__)
        finally:
            await self.db.whatsapp_sender_locks.delete_one(
                {"_id": item["phone_hash"], "owner": item_id},
            )
        return True


async def disconnect_account(db, user_id: str) -> None:
    """Revocation always works, even when Meta credentials are no longer set."""
    linked = await db.whatsapp_links.find_one({"user_id": user_id}, {"_id": 0})
    await db.whatsapp_link_codes.delete_many({"user_id": user_id})
    # Consent revocation is made durable before any pending alert is handled.
    await db.whatsapp_links.delete_many({"user_id": user_id})
    await db.whatsapp_alert_outbox.update_many(
        {"owner_id": user_id, "status": {"$in": ["ready", "held_template"]}},
        {"$set": {"status": "cancelled", "failure_code": "account_unlinked"}},
    )
    # Also discard messages received but not yet assigned a user_id.
    if linked:
        await db.whatsapp_inbox.update_many(
            {"phone_hash": linked["phone_hash"], "status": {"$in": ["received", "ready", "processing"]}},
            {"$set": {"status": "discarded", "phone_enc": None, "text_enc": None, "media_enc": None, "reply_enc": None}},
        )
    await db.whatsapp_inbox.update_many(
        {"reply_user_id": user_id, "status": {"$ne": "delivered"}},
        {"$set": {"status": "discarded", "phone_enc": None, "text_enc": None, "media_enc": None, "reply_enc": None}},
    )
