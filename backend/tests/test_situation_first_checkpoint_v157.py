OWNER = "owner_synthetic_v157"
OTHER = "another_owner_v157"


@pytest.fixture
def world(monkeypatch):
    monkeypatch.setenv("AMBIENT_RUNTIME", "1")
    return AsyncMongoMockClient().situation_first_checkpoint_v157


async def situation(db, *, owner=OWNER, sid="sit_test_watch", attentive=True):
    await db.agent_goals.create_index("id", unique=True)
    await db.agent_runs.create_index("goal_id", unique=True)
    await db.ambient_wakes.create_index(
        "identity", unique=True,
        partialFilterExpression={"status": {"$in": ["pending", "claimed"]}},
    )
    row = SituationState(
        id=sid, user_id=owner, session_id="test-session",
        summary="Ho iniziato un'attività temporanea; serve il prossimo riscontro",
        current_state_summary="Attività non terminata secondo l'utente",
        expected_outcome_summary="Quando sarà il momento utile per tornare",
        attention_intent="Rileggere le condizioni e capire se un aggiornamento serve" if attentive else None,
        temporal_scope="oggi",
        facts=["La persona ha iniziato adesso; l'esito non è confermato"],
        assumptions=["Non si conosce l'esito fisico"],
    )
    await SituationRepository(db).insert(row)
    return row


def model_scheduled(delay=25):
    return {
        "decision": "schedule",
        "check_at": (datetime.now(timezone.utc)+timedelta(minutes=delay)).isoformat(),
        "purpose": "Verificare se le informazioni disponibili sono cambiate",
        "completion_when": "è utile agire sulla situazione",
        "notify_when": "emerge una condizione imprevista che richiede attenzione",
        "reason": "Prima verifica dello stato con le fonti che saranno disponibili",
    }


@pytest.mark.asyncio
async def test_ai_chosen_first_checkpoint_is_an_actual_wake_and_idempotent(world, monkeypatch):
    from research import reasoning
    db = world
    await situation(db)
    calls = []

    async def decide(system, user):
        assert "NO first" not in user
        assert "openid" not in user
        assert "Live weather" in user
        calls.append(json.loads(user))
        return model_scheduled()

    monkeypatch.setattr(reasoning, "_ask_model", decide)
    result = await review_unattended(db, OWNER)
    assert result["scheduled"] == 1, result
    assert len(calls) == 1
    followup = await read_followup(db, OWNER, "sit_test_watch")
    assert followup["status"] == "scheduled"
    assert followup["next_check_at"]
    assert followup["next_check_label"]
    assert followup["last_checked_at"] is None
    assert await db.ambient_wakes.count_documents({
        "owner_id": OWNER, "status": "pending",
    }) == 1
    assert await db.agent_goals.count_documents({"owner_id": OWNER}) == 1
    assert (await review_unattended(db, OWNER))["scheduled"] == 0
    assert await db.ambient_wakes.count_documents({"owner_id": OWNER}) == 1
    assert len(calls) == 1
    # Wake for another owner is never generated by this pass.
    assert (await read_followup(db, OTHER, "sit_test_watch"))["status"] == "unavailable"


