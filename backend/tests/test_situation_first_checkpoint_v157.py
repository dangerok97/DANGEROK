@pytest.mark.asyncio
async def test_changed_revision_during_reasoning_must_not_schedule_stale_work(world, monkeypatch):
    from research import reasoning
    db = world
    await situation(db)
    async def decide(system, user):
        await db.situations.update_one(
            {"user_id": OWNER, "id": "sit_test_watch"},
            {"$set": {"status": "changed"}, "$inc": {"revision": 1}},
        )
        return model_scheduled()
    monkeypatch.setattr(reasoning, "_ask_model", decide)
    result = await review_unattended(db, OWNER)
    assert result["scheduled"] == 0
    assert await db.ambient_wakes.count_documents({}) == 0
    row = await decision_for(db, OWNER, "sit_test_watch", 1)
    assert row["status"] == "obsolete"
    assert await decision_for(db, OWNER, "sit_test_watch", 2) is None


